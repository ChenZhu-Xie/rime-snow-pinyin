// 只生成音节到标准二字词码的路由；候选和排序始终由运行中的 Rime 查询。
import { readFileSync, writeFileSync } from "node:fs";
import { SpellingAlgebra } from "./lib/algebra";
import { readDictionary } from "./lib/dictionary";
import { rootPath } from "./lib/paths";
import { SYLLABLE_PATTERNS } from "./lib/pinyin-validation";

export function pairCode(schema: string, first: string, last: string) {
	if (schema === "snow_sipin") return first.slice(0, 3) + last.slice(0, 3);
	if (schema === "snow_lanpin" || schema === "snow_sanpin") {
		return first.slice(0, 2) + last.slice(0, 2);
	}
	return first + last;
}

export function generateRoutes(
	schema: string,
	key: string,
	readings: string[],
) {
	const algebra = new SpellingAlgebra(rootPath(`${schema}.schema.yaml`), key);
	const tails = algebra.applyAll("shi4");
	const routes = new Map<string, Set<string>>();
	for (const reading of readings) {
		for (const code of algebra.applyAll(reading)) {
			const inputs = new Set<string>();
			for (let size = 1; size <= code.length; size++)
				inputs.add(code.slice(0, size));
			if (schema === "snow_sipin" && code.length === 3) inputs.add(`${code}o`);
			for (const input of inputs) {
				for (const tail of tails) {
					const route = `${input}\t${pairCode(schema, code, tail)}`;
					const values = routes.get(route) ?? new Set<string>();
					values.add(reading);
					routes.set(route, values);
				}
			}
		}
	}
	return (
		[...routes]
			.sort(([a], [b]) => a.localeCompare(b, "en"))
			.map(([route, values]) => `${route}\t${[...values].sort().join(" ")}`)
			.join("\n") + "\n"
	);
}

if (import.meta.main) {
	const readings = [
		...new Set(
			readDictionary(rootPath("snow_pinyin.dict.yaml"))
				.map(([, reading]) => reading)
				.filter((reading) => /^[a-zê]+[1-5]$/.test(reading)),
		),
	].sort();
	for (const { schema, key } of SYLLABLE_PATTERNS) {
		const content =
			"# Generated by scripts/generate-append-shi.ts; input\tstandard context code\treadings\n" +
			generateRoutes(schema, key, readings);
		const path = rootPath(`lua/snow/append_shi_${schema}.txt`);
		if (process.argv.includes("--check")) {
			if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== content)
				throw new Error(`${path} 需要重新生成`);
		} else writeFileSync(path, content);
		console.log(`${schema}: ${content.split("\n").length - 2} routes`);
	}
}
