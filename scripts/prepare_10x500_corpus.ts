import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// 从已有的神韵测评报告中提取第 10 篇（输入法赛文），严格 500 汉字，37 句
function loadArticle10(): string[] {
	const text = readFileSync(
		join(root, "reports", "神韵双拼八方案_500字_最短键码实战测评.txt"),
		"utf8",
	);
	const lines = text.split(/\r?\n/);
	const result: string[] = [];
	for (const line of lines) {
		if (line.startsWith("原文")) {
			// 去掉“原文”和多余排版空格
			const raw = line.slice("原文".length).replace(/\s+/gu, "");
			result.push(raw);
		}
	}
	return result;
}

export interface Corpus500 {
	id: number;
	title: string;
	genre: string;
	lines: string[];
}

// 辅助函数：统计纯汉字数
export function countHan(lines: string[]): number {
	return lines.reduce(
		(sum, line) =>
			sum + [...line].filter((c) => /\p{Script=Han}/u.test(c)).length,
		0,
	);
}

